import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));

/** Body of the Creed only, without the heading and source note. */
export function creedText(): string {
  const md = readFileSync(root('creed/nicene-creed-381.md'), 'utf8');
  return md.split('\n').filter((l) => l && !l.startsWith('#') && !l.startsWith('The Nicene-Constantinopolitan')).join('\n\n');
}

/** The system prompt every Always AI deployment uses. A church library, if given, is appended after it. */
export function systemPrompt(churchLibrary?: string): string {
  const base = readFileSync(root('instructions/always-ai.md'), 'utf8').replace('{{CREED}}', creedText()).trim();
  return churchLibrary?.trim() ? `${base}\n\n## Church library\n\n${churchLibrary.trim()}` : base;
}

/** Ollama Modelfile wrapping the base model with the Always AI instructions. */
export function modelfile(base = 'inkling-2-mini'): string {
  return [
    '# Generated by `npm run ai:modelfile`. Edit packages/ai/instructions or packages/ai/creed, not this file.',
    '# Set FROM to the Ollama tag or local path of Inkling 2 Mini on your machine.',
    `FROM ${base}`,
    'PARAMETER temperature 0.4',
    `SYSTEM """${systemPrompt().replace(/"""/g, '"​""')}"""`,
    '',
  ].join('\n');
}
